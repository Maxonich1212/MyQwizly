export const HABIT_ICONS = Object.fromEntries(LIST.map(([k, C]) => [k, C]))
const KEYWORDS = Object.fromEntries(LIST.map(([k, C, kw]) => [k, `${k} ${C.displayName || ''} ${kw}`.toLowerCase()]))

// Поиск по-русски и по-английски: «вода», «книга», «code»
export function searchIcons(q) {
  const n = q.trim().toLowerCase().replace(/ё/g, 'е')
  if (!n) return Object.keys(HABIT_ICONS)
  return Object.keys(HABIT_ICONS).filter((k) => KEYWORDS[k].replace(/ё/g, 'е').includes(n))
}

export default function HabitIcon({ name, size = 24, strokeWidth = 2 }) {
  const C = HABIT_ICONS[name] || Activity
  return <C size={size} strokeWidth={strokeWidth} />
}
